/**
 * Storage-layer data model and public contracts.
 *
 * Physical storage: IndexedDB (database `yatouch`).
 *
 * Conventions:
 * - `online` is a derived field and is NEVER persisted (see {@link StoredDevice});
 * - `DeviceRecord.protocol` / `ConnectionEvent.protocol` record the core protocol a
 *   connection used; the `CoreProtocol` type is an extensible union, so adding a new
 *   protocol (usb, ble, …) requires no schema change.
 */

import { Platform } from "../types";

/** Core transport protocol (extensible union). Current implementation is p2p (WebRTC DataChannel); usb direct link and others are planned. */
export type CoreProtocol = "p2p" | "usb" | (string & {});

/**
 * Device profile (public contract). `uuid` is the permanent system identity and an
 * internal identifier — it must NEVER be rendered in the UI.
 */
export interface DeviceRecord {
  /** Permanent identity, primary key. Internal only — never shown in the UI. */
  uuid: string;
  /** Hostname reported by the peer (hello handshake), nullable. */
  name: string | null;
  /** User remark, nullable. Display priority: remark > name > "Unknown device". */
  remark: string | null;
  platform: Platform | null;
  /** OS description, e.g. "Windows 11". */
  os: string | null;
  /** First registration time (epoch ms). */
  firstSeen: number;
  /** Last connection time (redundant projection aggregated from the event log, for list sorting). */
  lastSeen: number | null;
  /** Core protocol of the last connection (redundant projection; the fact source is `ConnectionEvent.protocol`). */
  protocol: CoreProtocol | null;
  /** Online status (derived, not persisted): true / false / null(Unknown). */
  online: boolean | null;
  /** Per-extension namespaced metadata: { "<extId>": {...} }. */
  meta: Record<string, unknown>;
}

/** Persisted shape: derived field `online` stripped. */
export type StoredDevice = Omit<DeviceRecord, "online">;

/** Connection event log: append-only, bounded retention (see MAX_CONNECTION_EVENTS). */
export interface ConnectionEvent {
  /** Auto-increment primary key (IndexedDB autoIncrement). */
  id: number;
  uuid: string;
  /** 'in' (inbound) / 'out' (outbound). */
  direction: "in" | "out";
  /** Initiating extension id; core (handshake) connections are null. */
  extension: string | null;
  /** Epoch ms. */
  time: number;
  /** Core protocol used by this connection. */
  protocol: CoreProtocol;
}

/** Input shape for appending/recording a connection (id is auto-generated by the store). */
export type NewConnectionEvent = Omit<ConnectionEvent, "id">;

/** IndexedDB database name and current schema version. */
export const DB_NAME = "yatouch";
export const DB_VERSION = 1;
/** Bounded event-log cap (FIFO trim). */
export const MAX_CONNECTION_EVENTS = 500;
